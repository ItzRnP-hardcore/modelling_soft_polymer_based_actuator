"""
export_ansys.py - Generate ANSYS Mechanical APDL (.mac / .inp) verification files
==================================================================================
Creates ready-to-run ANSYS APDL batch files to cross-check both parts of the BTP:

1. ansys/actuator_bare.mac
   - Exact 20-node SOLID186 mixed u-P mesh exported from actuator_fea.py
   - Half-symmetry eccentric-cavity silicone actuator (R=10, r=4, rp=3, L=100 mm)
   - Neo-Hookean hyperelasticity (C10 = 0.1 MPa, d = 2/kappa for nu = 0.4995)
   - Follower pressure on cavity faces via SURF154
   - Writes P vs tip deflection & angle to ansys_bare_summary.csv

2. ansys/actuator_sleeve.mac
   - Same SOLID186 mesh + ideal hoop-fibre reinforcement on outer surface
   - Uses anisotropic membrane/shell SURF/SHELL elements or orthotropic outer skin
   - Writes P vs tip deflection & angle to ansys_sleeve_summary.csv

3. ansys/grasp_2d_verify.mac
   - Planar 2-finger grasp & pull-down verification using BEAM188 + CONTA175/TARGE170
   - Matches grasp_model.py (L=100 mm, R=10 mm, t=2 mm, E=0.15 MPa, a=15 mm, depth=70 mm)
   - Applies thermal-analog spontaneous curvature kappa0(P) and pulls cylinder down
   - Writes pull vs holding force Fy to ansys_grasp_summary.csv

Usage:
    python export_ansys.py [--mesh coarse|medium]
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "grasp"))

from actuator_model import Geometry, Material
import actuator_fea as fea
from grasp_model import Finger

# Map our 27-node hex (lexicographic a + 3b + 9c, a,b,c in {0,1,2} for {-1,0,+1})
# to ANSYS SOLID186 20-node serendipity ordering (1-based indices in 0..26):
# Corner nodes:
#   1:(-1,-1,-1)=0,  2:(+1,-1,-1)=2,  3:(+1,+1,-1)=8,  4:(-1,+1,-1)=6
#   5:(-1,-1,+1)=18, 6:(+1,-1,+1)=20, 7:(+1,+1,+1)=26, 8:(-1,+1,+1)=24
# Midside nodes:
#   9:(0,-1,-1)=1,  10:(+1,0,-1)=5,  11:(0,+1,-1)=7,  12:(-1,0,-1)=3
#  13:(0,-1,+1)=19, 14:(+1,0,+1)=23, 15:(0,+1,+1)=25, 16:(-1,0,+1)=21
#  17:(-1,-1,0)=9,  18:(+1,-1,0)=11, 19:(+1,+1,0)=17, 20:(-1,+1,0)=15
HEX27_TO_SOLID186 = [
    0, 2, 8, 6, 18, 20, 26, 24,
    1, 5, 7, 3, 19, 23, 25, 21,
    9, 11, 17, 15
]

# Map our 9-node quad (a + 3b, a,b in {0,1,2}) to ANSYS 8-node surface/shell:
#   1:(-1,-1)=0, 2:(+1,-1)=2, 3:(+1,+1)=8, 4:(-1,+1)=6
#   5:(0,-1)=1,  6:(+1,0)=5,  7:(0,+1)=7,  8:(-1,0)=3
QUAD9_TO_SURF8 = [0, 2, 8, 6, 1, 5, 7, 3]


def write_actuator_apdl(path: Path, g: Geometry, mat: Material, mesh_name="medium",
                        nu=0.4995, sleeve=False, pmax_kpa=100.0, steps=20):
    m, fe = fea.make_actuator(g, mat, mesh=mesh_name, nu=nu, sleeve=sleeve)
    X = m["X"]
    conn20 = m["conn"][:, HEX27_TO_SOLID186] + 1       # 1-based ANSYS node IDs
    cav8 = m["cav"][:, QUAD9_TO_SURF8] + 1
    outer8 = m["outer"][:, QUAD9_TO_SURF8] + 1
    d_incomp = 2.0 / fe.kappa                          # ANSYS neo-Hookean incompressibility parameter d = 2/K

    tip_top_node = int(m["top"][m["iL"]]) + 1
    tip_bot_node = int(m["bot"][m["iL"]]) + 1

    variant = "sleeve" if sleeve else "bare"
    lines = [
        f"! ==========================================================================",
        f"! ANSYS APDL Verification Deck: Eccentric-Cavity Soft Actuator ({variant.upper()})",
        f"! Generated by export_ansys.py from actuator_fea.py ({mesh_name} mesh)",
        f"! Geometry: R={g.R} mm, r={g.r} mm, rp={g.rp} mm, L={g.L} mm, t_cap={m['t_cap']} mm",
        f"! Material: Neo-Hookean E={mat.E} MPa (C10={mat.C10} MPa, nu={nu}, d={d_incomp:.6e} MPa^-1)",
        f"! Units: mm, N, MPa",
        f"! Run in batch:  mapdl -b -i {path.name} -o {path.stem}.out",
        f"! ==========================================================================",
        "/BATCH",
        "/CLEAR,NOSTART",
        f"/FILNAME,actuator_{variant},1",
        "/PREP7",
        "",
        "! --- 1. Element types ---",
        "ET,1,SOLID186          ! 20-node quadratic brick",
        "KEYOPT,1,2,0           ! Uniform reduced integration",
        "KEYOPT,1,6,1           ! Mixed u-P formulation (prevents volumetric locking)",
        "ET,2,SURF154           ! 3-D structural surface effect for follower cavity pressure",
        "KEYOPT,2,4,0           ! Include midside nodes",
    ]

    if sleeve:
        lines += [
            "ET,3,SHELL281          ! 8-node quadratic shell on outer surface for hoop sleeve",
            "KEYOPT,3,1,1           ! Membrane stiffness only (no bending stiffness)",
            "SECTYPE,3,SHELL",
            "SECDATA,0.1,2,90.0,3   ! t=0.1 mm, material 2, oriented 90 deg (hoop direction)",
        ]

    lines += [
        "",
        "! --- 2. Material properties ---",
        "TB,HYPER,1,1,2,NEO     ! Neo-Hookean hyperelastic silicone",
        f"TBDATA,1,{mat.C10:.8f},{d_incomp:.8e}",
    ]

    if sleeve:
        # Orthotropic membrane with hoop stiffness E_hoop * t_shell = 100 * E * R -> E_hoop = 1000 * E * R
        E_hoop = (100.0 * mat.E * g.R) / 0.1
        lines += [
            "! Ideal hoop-fibre sleeve: stiff in hoop (local x rotated 90 deg), negligible axial stiffness",
            f"MP,EX,2,{E_hoop:.4f}",
            f"MP,EY,2,{1e-4 * mat.E:.6e}",
            f"MP,EZ,2,{1e-4 * mat.E:.6e}",
            "MP,PRXY,2,0.0",
            "MP,PRYZ,2,0.0",
            "MP,PRXZ,2,0.0",
            f"MP,GXY,2,{1e-3 * mat.E:.6e}",
            f"MP,GYZ,2,{1e-3 * mat.E:.6e}",
            f"MP,GXZ,2,{1e-3 * mat.E:.6e}",
            "! Cylindrical coordinate system with axis along global X for hoop fibre orientation",
            "LOCAL,11,1,0,0,0,0,90,0",
            "ESYS,11",
        ]

    lines += ["", "! --- 3. Nodes ---"]
    for idx, (x, y, z) in enumerate(X, start=1):
        lines.append(f"N,{idx},{x:.8f},{y:.8f},{z:.8f}")

    lines += ["", "! --- 4. SOLID186 Volume Elements ---", "TYPE,1", "MAT,1", "ESYS,0"]
    for eid, enodes in enumerate(conn20, start=1):
        n_part1 = ",".join(str(n) for n in enodes[:8])
        n_part2 = ",".join(str(n) for n in enodes[8:])
        lines.append(f"EN,{eid},{n_part1}")
        lines.append(f"EMORE,{n_part2}")

    next_eid = len(conn20) + 1
    lines += ["", "! --- 5. SURF154 Cavity Pressure Faces ---", "TYPE,2", "MAT,1"]
    cav_eids = []
    for fnodes in cav8:
        n_str = ",".join(str(n) for n in fnodes)
        lines.append(f"EN,{next_eid},{n_str}")
        cav_eids.append(next_eid)
        next_eid += 1
    lines.append(f"CM,CAV_SURF,ELEM")

    if sleeve:
        lines += ["", "! --- 6. SHELL281 Outer Hoop Sleeve ---", "TYPE,3", "MAT,2", "SECNUM,3", "ESYS,11"]
        for fnodes in outer8:
            n_str = ",".join(str(n) for n in fnodes)
            lines.append(f"EN,{next_eid},{n_str}")
            next_eid += 1

    lines += [
        "",
        "! --- 7. Boundary Conditions ---",
        "! Clamp base x = 0",
    ]
    for nid in (m["base"] + 1):
        lines.append(f"D,{nid},ALL,0.0")
    lines.append("! Symmetry plane z = 0 (uz = 0)")
    for nid in (m["sym"] + 1):
        lines.append(f"D,{nid},UZ,0.0")

    lines += [
        "FINISH",
        "",
        "! --- 8. Nonlinear Solution ---",
        "/SOLU",
        "ANTYPE,STATIC",
        "NLGEOM,ON              ! Large-deflection follower pressure & finite strain",
        "AUTOTS,ON",
        f"NSUBST,{steps},{steps * 5},{steps}",
        "OUTRES,ALL,ALL",
        "",
        f"! Apply follower pressure P = {pmax_kpa:.3f} kPa ({pmax_kpa / 1e3:.6f} MPa) on cavity faces (face 1 of SURF154)",
        f"ESEL,S,TYPE,,2",
        f"SFE,ALL,1,PRES,,{pmax_kpa / 1e3:.6f}",
        "ALLSEL,ALL",
        "SOLVE",
        "FINISH",
        "",
        "! --- 9. Post-processing: export P, tip deflection delta, tip angle theta ---",
        "/POST26",
        f"NSOL,2,{tip_top_node},U,X,UX_TOP",
        f"NSOL,3,{tip_top_node},U,Y,UY_TOP",
        f"NSOL,4,{tip_bot_node},U,X,UX_BOT",
        f"NSOL,5,{tip_bot_node},U,Y,UY_BOT",
        f"*CFOPEN,ansys_{variant}_summary,csv",
        "*VWRITE,'P_kPa,x_tip_mm,delta_mm,theta_deg'",
        "(A)",
        "*GET,NSETS,ACTIVE,0,SET,NSET",
        "/POST1",
        "*DO,ISET,1,NSETS",
        "  SET,1,ISET",
        "  *GET,TFAC,ACTIVE,0,SET,TIME",
        f"  P_KPA = TFAC * {pmax_kpa:.6f}",
        f"  X_TOP = NX({tip_top_node}) + UX({tip_top_node})",
        f"  Y_TOP = NY({tip_top_node}) + UY({tip_top_node})",
        f"  X_BOT = NX({tip_bot_node}) + UX({tip_bot_node})",
        f"  Y_BOT = NY({tip_bot_node}) + UY({tip_bot_node})",
        "  X_TIP = 0.5 * (X_TOP + X_BOT)",
        "  DELTA = -0.5 * (Y_TOP + Y_BOT)",
        "  THETA_DEG = ATAN2(X_TOP - X_BOT, Y_TOP - Y_BOT) * 180.0 / 3.141592653589793",
        "  *VWRITE,P_KPA,X_TIP,DELTA,THETA_DEG",
        "  (F10.4,',',F12.5,',',F12.5,',',F12.5)",
        "*ENDDO",
        "*CFCLOSE",
        "FINISH",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return len(X), len(conn20)


def write_grasp_apdl(path: Path, P_kpa=50.0, depth=70.0, mu=0.6, a_obj=15.0, pull=40.0):
    f = Finger(L=100.0, R0=10.0, Rt=10.0, t0=2.0, tt=2.0, E=0.15, N=100)
    _, EI, mp = f.sections()
    EI_val = float(EI[0])
    kap0 = float(f.kappa0(P_kpa * 1e-3)[0])
    # Represent rod with equivalent rectangular section of height h=2 mm, width b_eq = 12*EI/(E*h^3)
    h_eq = 2.0
    b_eq = 12.0 * EI_val / (f.E * h_eq**3)
    b_palm = a_obj + 1.0

    lines = [
        "! ==========================================================================",
        "! ANSYS APDL Verification Deck: Planar 2-Finger Pneumatic Grasp & Pull-out",
        "! Matches grasp_model.py baseline (Uniform finger, P=50 kPa, mu=0.6, depth=70 mm)",
        f"! EI = {EI_val:.2f} N*mm^2, kappa0(50 kPa) = {kap0:.6f} mm^-1 (free tip angle = {np.degrees(kap0*f.L):.2f} deg)",
        "! Spontaneous curvature applied via thermal-gradient analog (alpha * dT/dy = kappa0)",
        "! Run in batch:  mapdl -b -i grasp_2d_verify.mac -o grasp_2d_verify.out",
        "! ==========================================================================",
        "/BATCH",
        "/CLEAR,NOSTART",
        "/FILNAME,grasp_2d_verify,1",
        "/PREP7",
        "",
        "! --- 1. Element Types & Material ---",
        "ET,1,BEAM188           ! 3-D quadratic/linear Timoshenko beam",
        "KEYOPT,1,3,2           ! Quadratic shape functions along length",
        "MP,EX,1,0.15           ! E = 0.15 MPa",
        "MP,PRXY,1,0.49",
        "MP,ALPX,1,1.0          ! Unit thermal expansion for spontaneous curvature kappa0",
        "MP,MU,1,0.6            ! Coulomb friction coefficient mu = 0.6",
        "",
        f"SECTYPE,1,BEAM,RECT",
        f"SECDATA,{h_eq:.4f},{b_eq:.4f},2,2",
        "",
        "! --- 2. Finger Nodes & Elements (Left finger at x = -16 mm, y = 0..-100 mm) ---",
    ]
    for i in range(f.N + 1):
        y = -i * f.ds
        lines.append(f"N,{i + 1},{-b_palm:.4f},{y:.4f},0.0")
    lines.append("N,999,0.0,-50.0,10.0   ! Orientation node for BEAM188")
    lines.append("TYPE,1 $ MAT,1 $ SECNUM,1")
    for i in range(f.N):
        lines.append(f"E,{i + 1},{i + 2},999")

    lines += [
        "",
        "! --- 3. Rigid Cylinder Target (TARGE170) & Contact (CONTA175) ---",
        "ET,2,TARGE170",
        "ET,3,CONTA175",
        "KEYOPT,3,2,1           ! Penalty contact (matches grasp_model.py)",
        "KEYOPT,3,12,0          ! Standard frictional unilateral contact",
        "R,2," + f"{a_obj:.4f}          ! Cylinder radius a = 15 mm",
        "RMODIF,2,3,-20.0       ! Normal penalty stiffness kn = 20 N/mm",
        f"N,500,0.0,{-depth:.4f},0.0   ! Cylinder pilot/centre node",
        "TYPE,2 $ REAL,2",
        "TSHAP,CYL2             ! 2-D rigid circle in X-Y plane",
        "E,500",
        "TSHAP,PILO",
        "E,500",
        "TYPE,3 $ REAL,2 $ MAT,1",
    ]
    for i in range(1, f.N + 1):
        lines.append(f"E,{i + 1}")

    lines += [
        "",
        "! --- 4. Boundary Conditions ---",
        "D,1,ALL,0.0            ! Clamp finger base at palm (x=-16, y=0)",
        "D,ALL,UZ,0.0           ! Planar constraint",
        "D,ALL,ROTX,0.0 $ D,ALL,ROTY,0.0",
        "D,500,ALL,0.0          ! Hold cylinder fixed during inflation",
        "FINISH",
        "",
        "! --- 5. Load Step 1: Inflate 0 -> 50 kPa (spontaneous curvature kappa0) ---",
        "/SOLU",
        "ANTYPE,STATIC",
        "NLGEOM,ON",
        "NSUBST,25,100,25",
        f"BFE,ALL,TEMP,1,0.0,{kap0:.8f},0.0   ! Through-thickness gradient = kappa0",
        "SOLVE",
        "",
        "! --- 6. Load Step 2: Pull Cylinder Down by 40 mm ---",
        "NSUBST,80,400,80",
        f"D,500,UY,{-pull:.4f}",
        "OUTRES,ALL,ALL",
        "SOLVE",
        "FINISH",
        "",
        "! --- 7. Post-processing: Export Pull vs Holding Force (2 * Fy_pilot) ---",
        "/POST1",
        "*CFOPEN,ansys_grasp_summary,csv",
        "*VWRITE,'pull_mm,Fy_two_fingers_N'",
        "(A)",
        "*GET,NSETS,ACTIVE,0,SET,NSET",
        "*DO,ISET,1,NSETS",
        "  SET,2,ISET",
        "  PULL_MM = -UY(500)",
        "  *GET,FY_ONE,NODE,500,RF,FY",
        "  FY_TWO = -2.0 * FY_ONE",
        "  *VWRITE,PULL_MM,FY_TWO",
        "  (F10.4,',',F12.5)",
        "*ENDDO",
        "*CFCLOSE",
        "FINISH",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Generate ANSYS APDL verification files.")
    ap.add_argument("--mesh", choices=["coarse", "medium"], default="medium")
    args = ap.parse_args()

    outdir = HERE
    outdir.mkdir(exist_ok=True)
    g = Geometry(R=10.0, r=4.0, rp=3.0, L=100.0)
    mat = Material.from_E(0.6)

    nn, ne = write_actuator_apdl(outdir / "actuator_bare.mac", g, mat, mesh_name=args.mesh,
                                 sleeve=False, pmax_kpa=100.0, steps=20)
    print(f"Wrote {outdir / 'actuator_bare.mac'} ({nn} nodes, {ne} SOLID186 elements)")

    nn, ne = write_actuator_apdl(outdir / "actuator_sleeve.mac", g, mat, mesh_name=args.mesh,
                                 sleeve=True, pmax_kpa=110.0, steps=22)
    print(f"Wrote {outdir / 'actuator_sleeve.mac'} ({nn} nodes, {ne} SOLID186 elements + SHELL281 hoop sleeve)")

    write_grasp_apdl(outdir / "grasp_2d_verify.mac")
    print(f"Wrote {outdir / 'grasp_2d_verify.mac'} (BEAM188 + CONTA175/TARGE170 planar grasp)")

